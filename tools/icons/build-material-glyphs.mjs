#!/usr/bin/env node
/**
 * Generates `libs/ui/icons/src/lib/material/material-glyphs.generated.ts`:
 * the path data of every Material Symbol the bundled vocabulary names, at
 * the house cut (Rounded · FILL 1 · wght 400 · GRAD 0 · opsz 24), fetched
 * from a PINNED revision of google/material-design-icons.
 *
 * Why a generated table and not the icon font or the npm SVG package:
 *   - the variable ligature font is 5.1 MB and renders a glyph's NAME in
 *     capitals when the name is unknown to it — a failure nothing caught
 *     at build time;
 *   - `@material-symbols/svg-*` ships only the 48 px optical size, and the
 *     house look is pinned to 24;
 *   - path data renders synchronously — no font load, no flash, no shift.
 *
 * Usage:
 *   node tools/icons/build-material-glyphs.mjs            # (re)generate
 *   node tools/icons/build-material-glyphs.mjs --check    # offline: table covers the vocabulary
 *
 * Bumping the icon set = changing MATERIAL_DESIGN_ICONS_COMMIT and regenerating.
 * The vocabulary is loaded through `load-ts.mjs` (transpiled, no bundler).
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { importTs } from './load-ts.mjs';

const MATERIAL_DESIGN_ICONS_COMMIT = '27e9ef1dbeedc13d682fece4a58e1eda4cb0961a';
const STYLE = 'rounded';
const VARIANT = 'fill1_24px';
const CONCURRENCY = 8;

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const vocabularyPath = join(
  root,
  'libs/ui/icons/src/lib/manifest/icon-vocabulary.ts',
);
const outputPath = join(
  root,
  'libs/ui/icons/src/lib/material/material-glyphs.generated.ts',
);

const { UI_ICON_REGISTRY } = await importTs(vocabularyPath);
const glyphs = [...new Set(Object.values(UI_ICON_REGISTRY))].sort();

if (process.argv.includes('--check')) {
  // Import the table rather than grepping its text, so formatting can
  // neither fake a stale table nor hide one.
  const { MATERIAL_GLYPHS } = await importTs(outputPath);
  const missing = glyphs.filter(
    (glyph) => !Object.prototype.hasOwnProperty.call(MATERIAL_GLYPHS, glyph),
  );
  if (missing.length > 0) {
    console.error(
      `material-glyphs.generated.ts is stale — missing: ${missing.join(', ')}`,
    );
    console.error('Run: node tools/icons/build-material-glyphs.mjs');
    process.exit(1);
  }
  console.log(`ok — ${glyphs.length} glyphs covered`);
  process.exit(0);
}

const urlFor = (glyph) =>
  `https://raw.githubusercontent.com/google/material-design-icons/${MATERIAL_DESIGN_ICONS_COMMIT}` +
  `/symbols/web/${glyph}/materialsymbols${STYLE}/${glyph}_${VARIANT}.svg`;

const PATH_D = /<path d="([^"]+)"\s*\/>/;
const VIEW_BOX = 'viewBox="0 -960 960 960"';

async function fetchGlyph(glyph) {
  const response = await fetch(urlFor(glyph));
  if (response.status === 404) {
    throw new Error(
      `"${glyph}" does not exist in Material Symbols ${STYLE} at ${MATERIAL_DESIGN_ICONS_COMMIT.slice(0, 7)} — fix the vocabulary`,
    );
  }
  if (!response.ok) throw new Error(`${glyph}: HTTP ${response.status}`);
  const svg = await response.text();
  if (!svg.includes(VIEW_BOX)) throw new Error(`${glyph}: unexpected viewBox`);
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)];
  if (paths.length !== 1 || !PATH_D.test(svg)) {
    throw new Error(
      `${glyph}: expected exactly one <path>, got ${paths.length}`,
    );
  }
  return paths[0][1];
}

const table = new Map();
const queue = [...glyphs];
const failures = [];
await Promise.all(
  Array.from({ length: CONCURRENCY }, async () => {
    while (queue.length > 0) {
      const glyph = queue.shift();
      try {
        table.set(glyph, await fetchGlyph(glyph));
      } catch (error) {
        failures.push(error instanceof Error ? error.message : String(error));
      }
    }
  }),
);
if (failures.length > 0) {
  console.error(failures.join('\n'));
  process.exit(1);
}

const entries = [...table.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([glyph, d]) => `  ${JSON.stringify(glyph)}:\n    ${JSON.stringify(d)},`)
  .join('\n');

const bytes = [...table.values()].reduce((sum, d) => sum + d.length, 0);

writeFileSync(
  outputPath,
  `/* AUTO-GENERATED by tools/icons/build-material-glyphs.mjs — DO NOT EDIT.
 * Re-run \`pnpm icons:glyphs\` after changing UI_ICON_REGISTRY or the pin.
 * ${table.size} glyphs · ${bytes.toLocaleString('en-US')} bytes of path data.
 */
/* eslint-disable */

/** Provenance of every path below — the pin is the version of the icon set. */
export const MATERIAL_GLYPHS_SOURCE = {
  repository: 'google/material-design-icons',
  commit: '${MATERIAL_DESIGN_ICONS_COMMIT}',
  style: '${STYLE}',
  fill: 1,
  weight: 400,
  grade: 0,
  opticalSize: 24,
} as const;

/** Material Symbol name → SVG path data on the \`0 -960 960 960\` viewBox. */
export const MATERIAL_GLYPHS: Readonly<Record<string, string>> = {
${entries}
};
`,
);
console.log(
  `wrote ${table.size} glyphs (${bytes.toLocaleString('en-US')} bytes) to ${outputPath}`,
);
